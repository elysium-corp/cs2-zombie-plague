namespace Admin.Api.Data;

/// <summary>
/// Представляет зарегистрированную привилегию, которая описывает набор разрешений,
/// доступных игроку при наличии соответствующего назначения.
/// </summary>
/// <remarks>
/// Привилегия описывает только то, какие возможности она предоставляет.
/// Информация о том, какому игроку она назначена и до какого момента действует,
/// хранится отдельно.
///
/// Уникальный ключ привилегии формируется в формате <c>group.id</c>,
/// например <c>admin.owner</c> или <c>vip.premium</c>.
/// </remarks>
public interface IPrivilege
{
    /// <summary>
    /// Получает идентификатор привилегии внутри её группы.
    /// </summary>
    /// <example>
    /// Для привилегии <c>admin.owner</c> идентификатором является <c>owner</c>.
    /// </example>
    string Id { get; }

    /// <summary>
    /// Получает логическую группу привилегии.
    /// </summary>
    /// <example>
    /// Для привилегии <c>admin.owner</c> группой является <c>admin</c>.
    /// </example>
    string Group { get; }
    
    /// <summary>
    /// Получает полный уникальный ключ привилегии в формате <c>group.id</c>.
    /// </summary>
    /// <example>
    /// <c>admin.owner</c>, <c>admin.moderator</c>, <c>vip.premium</c>.
    /// </example>
    string Key { get; }

    /// <summary>
    /// Получает неизменяемый набор разрешений, предоставляемых данной привилегией.
    /// </summary>
    /// <remarks>
    /// Сравнение разрешений выполняется без учёта регистра.
    /// </remarks>
    IReadOnlySet<string> Permissions { get; }
}